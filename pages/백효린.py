import streamlit as st
import random

# ----------------------------
# 기본 설정
# ----------------------------
st.set_page_config(
    page_title="시험기간 마음 회복 스테이션",
    page_icon="🌱",
    layout="centered"
)

# ----------------------------
# 데이터
# ----------------------------

stress_tips = {
    "공부가 너무 안 돼요": [
        "25분 집중 + 5분 휴식 방식으로 시작해보세요.",
        "완벽하게 하려 하지 말고 가장 쉬운 문제부터 풀어보세요.",
        "공부 목표를 '한 챕터'가 아니라 '10분 집중'처럼 작게 나눠보세요."
    ],
    "시험 결과가 걱정돼요": [
        "결과보다 지금 할 수 있는 행동 하나에 집중해보세요.",
        "시험은 자신의 가치를 평가하는 기준이 아닙니다.",
        "걱정 시간을 정해두고 그 외 시간에는 현재 공부에 집중해보세요."
    ],
    "잠이 부족하고 피곤해요": [
        "잠들기 30분 전에는 휴대폰 사용을 줄여보세요.",
        "짧은 낮잠(10~20분)은 집중력 회복에 도움이 됩니다.",
        "오늘 할 공부량을 조금 줄이고 회복 시간을 확보하세요."
    ],
    "마음이 답답하고 불안해요": [
        "천천히 5번 깊게 호흡하며 몸의 긴장을 풀어보세요.",
        "걱정을 글로 적으면 생각이 정리되는 데 도움이 됩니다.",
        "믿을 수 있는 친구나 가족에게 마음을 이야기해보세요."
    ]
}


# ----------------------------
# 화면
# ----------------------------

st.title("🌱 시험기간 마음 회복 스테이션")
st.write(
    "시험 때문에 힘든 마음을 확인하고, 지금 필요한 회복 방법을 찾아보세요."
)

st.divider()


# ----------------------------
# 스트레스 검사
# ----------------------------

st.subheader("📊 나의 시험 스트레스 체크")

score = 0

q1 = st.radio(
    "1. 시험 생각을 하면 긴장되거나 불안한가요?",
    ["전혀 아니다", "조금 그렇다", "많이 그렇다"]
)

q2 = st.radio(
    "2. 공부를 시작하기 어려운가요?",
    ["전혀 아니다", "조금 그렇다", "많이 그렇다"]
)

q3 = st.radio(
    "3. 피곤하거나 잠이 부족한가요?",
    ["전혀 아니다", "조금 그렇다", "많이 그렇다"]
)

mapping = {
    "전혀 아니다": 0,
    "조금 그렇다": 1,
    "많이 그렇다": 2
}

score = (
    mapping[q1]
    + mapping[q2]
    + mapping[q3]
)

if st.button("스트레스 결과 보기"):
    st.success(f"현재 스트레스 점수: {score}/6")

    if score <= 2:
        st.info("현재 상태는 비교적 안정적이에요. 지금 페이스를 유지해보세요 😊")
    elif score <= 4:
        st.warning(
            "스트레스가 조금 쌓이고 있어요. 휴식과 공부 균형이 필요해요."
        )
    else:
        st.error(
            "스트레스가 높은 상태로 보여요. 잠깐 쉬고 주변 사람에게 도움을 요청하는 것도 좋아요."
        )


st.divider()


# ----------------------------
# 맞춤 추천
# ----------------------------

st.subheader("💡 맞춤 스트레스 해소법")

choice = st.selectbox(
    "현재 가장 가까운 상태를 선택하세요",
    list(stress_tips.keys())
)

if st.button("추천 받기"):
    try:
        tip = random.choice(stress_tips[choice])
        st.success(tip)

    except Exception:
        st.error("추천을 불러오는 중 문제가 발생했습니다.")


st.divider()


# ----------------------------
# 오늘의 루틴
# ----------------------------

st.subheader("📝 오늘의 작은 회복 루틴")

if st.button("오늘 루틴 만들기"):
    routines = [
        "✅ 물 한 컵 마시기",
        "✅ 10분 스트레칭하기",
        "✅ 가장 쉬운 공부 15분 시작하기",
        "✅ 잠들기 전 걱정 적어보기",
        "✅ 좋아하는 음악 1곡 듣기"
    ]

    st.write("오늘은 이것만 해도 충분해요!")

    for r in random.sample(routines, 3):
        st.write(r)


st.divider()


# ----------------------------
# 마음 기록장
# ----------------------------

st.subheader("💬 마음 기록장")

text = st.text_area(
    "지금 내 마음을 자유롭게 적어보세요",
    placeholder="예) 시험이 걱정되지만 조금씩 해볼 수 있을 것 같다..."
)

if st.button("기록 확인"):
    if text.strip():
        st.success("기록 완료! 마음을 정리하는 좋은 습관이에요 🌱")
    else:
        st.warning("내용을 조금 입력해 주세요.")


st.divider()

st.caption(
    "이 앱은 자기 관리와 스트레스 완화를 위한 도구이며, "
    "심한 불안이나 힘든 감정이 지속된다면 믿을 수 있는 어른이나 전문가와 상담해보세요."
)
